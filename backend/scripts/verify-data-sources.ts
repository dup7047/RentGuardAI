/**
 * Phase 0.3 acceptance verifier.
 *
 * Hits every NYC Open Data Socrata endpoint listed in `docs/data-sources.md`
 * with `$limit=1`, asserts the response is HTTP 200, and asserts the
 * documented primary-key field is present in the returned row.
 *
 * Reads `NYC_OPEN_DATA_APP_TOKEN` from env if set (raises rate limit from
 * ~1k/hr to ~10k/hr per token, but the script works without one).
 *
 * Run:
 *   npm run verify:data-sources
 *   NYC_OPEN_DATA_APP_TOKEN=xxx npm run verify:data-sources
 *
 * Exits with code 0 on full pass, 1 on any failure. CI-friendly.
 */

import { config as loadDotenv } from "dotenv";

export interface Endpoint {
  /** Human label for log output. */
  label: string;
  /** Socrata resource id. */
  resourceId: string;
  /** Field that must exist in any non-empty response (the documented PK). */
  primaryKey: string;
  /**
   * Primary keys we'll accept in addition to the canonical one. Useful for
   * datasets where Socrata's stable id is the autogenerated `:id` rather
   * than a domain field — we treat `:id` as a valid fallback so the script
   * doesn't false-fail on schema drift.
   */
  alternatePrimaryKeys?: string[];
}

